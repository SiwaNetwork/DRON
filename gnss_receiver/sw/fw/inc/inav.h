/* МГП-8: навигационное сообщение Galileo I/NAV, сигнал E1-B (Galileo OS SIS ICD, п. 4.1.4, 4.3).
 * Страница — 2 с: чётная и нечётная части по 250 символов (символ — период кода E1-B, 4 мс):
 * синхрокомбинация 0101100000 и 240 символов (свёрточный код 1/2, K = 7, G1 = 171, G2 = 133
 * с инверсией, блочное перемежение 30 × 8). Слово — 128 бит (112 бит чётной и 16 бит нечётной
 * части), проверка — CRC-24Q по 196 битам. Слова 1–4 — эфемериды и часы (одна редакция IODnav),
 * 5 — ионосфера, BGD, состояние, WN/TOW, 6 — GST−UTC, TOW, 0 — WN/TOW. Время — GST: секунды
 * недели совпадают с GPST (без GGTO), неделя GPS = WN + 1024. TOW — GST начала страницы
 * (передний фронт синхрокомбинации чётной части). */
#ifndef INAV_H
#define INAV_H
#include <stdint.h>
#include "eph.h"

#define INAV_PART 250            /* символов в части страницы */
#define INAV_SYNC 10             /* символов синхрокомбинации */

typedef struct {
    int      prn;
    float    sym[INAV_PART + INAV_SYNC];   /* последние символы (мягкие значения, > 0 — лог. 0) */
    int      nsym;
    int      sync, pol, miss;    /* синхронизация по частям страницы, инверсия, пропуски */
    int      cnt;                /* символов текущей части */
    uint32_t part;               /* номер части с момента синхронизации */
    uint8_t  even[15];           /* последняя чётная часть: 114 бит */
    uint32_t even_part;          /* её номер */
    int      even_ok;
    int      wtype;              /* тип последнего принятого слова */
    uint8_t  word[16];           /* последнее слово: 128 бит */
    int      iod[4];             /* IODnav принятых слов 1–4 (−1 — нет) */
    int      w5;                 /* принято слово 5 (BGD, состояние КА) */
    eph_t    cur;                /* сборка эфемерид по словам 1–4 */
    eph_t    eph;                /* последние полные эфемериды */
    int      eph_new;
    double   ai[3];              /* ai0..ai2 (NeQuick-G) */
    int      ai_ok;
    double   utc_a0, utc_a1;
    int      dt_ls, utc_ok;
    int      week;               /* неделя GPS (WN + 1024), 0 — неизвестна */
    /* привязка ко времени: TOW (GST начала страницы) с номером её чётной части */
    int      tow_ok;
    double   tow_ref;
    uint32_t tow_part;
    /* последняя принятая страница: номер последнего отсчёта и GST её начала (если tow_ok) */
    uint64_t page_end_n;
    double   page_tow;
    int      n_page, n_crc_err;
} inav_t;

void inav_init(inav_t *g, int prn);
/* очередной символ (4 мс): мягкое значение (> 0 — логический 0), n_end — номер последнего
 * отсчёта символа. Возвращает 1, если принята страница с верной CRC (тип слова — g->wtype;
 * при g->tow_ok момент n_end + 1 соответствует GST g->page_tow + 2 с). */
int  inav_sym(inav_t *g, double v, uint64_t n_end);

/* кодирование (для проверок и имитатора): страница со словом wtype (0–6 — из эфемерид; прочие
 * типы — псевдослучайные данные); tow — GST начала страницы, week — неделя GPS. 500 символов
 * (0/1): чётная часть, затем нечётная. */
void inav_encode_page(const eph_t *e, int wtype, int tow, int week, uint8_t sym[500]);
/* служебные (для проверок): CRC-24Q по nbit битам (старший бит первым) */
uint32_t inav_crc24q(const uint8_t *b, int nbit);

#endif
