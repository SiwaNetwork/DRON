/* МГП-8: навигационное сообщение ГЛОНАСС L1OF/L2OF (ИКД ГЛОНАСС ред. 5.1, п. 3.3, 4.3–4.5).
 * Строка — 2 с: 85 бит данных в относительном коде с меандром (символы 10 мс), затем метка
 * времени из 30 символов. Строки 1–4 — оперативная информация (эфемериды ПЗ-90, τn, γn),
 * строка 5 — NA, τc, N4. Время — по шкале ГЛОНАСС (МДВ = UTC(SU) + 3 ч). */
#ifndef GLONAV_H
#define GLONAV_H
#include <stdint.h>
#include "eph.h"

#define GLO_STR_BITS 85
#define GLO_TM_LEN   30

typedef struct {
    int      fcn;            /* литера канала */
    /* поток символов (10 мс), мягкие значения */
    float    sym[230];
    int      nsym;           /* принято символов (всего) */
    int      sync, rev;      /* синхронизация по метке времени, инверсия */
    uint8_t  str[5][GLO_STR_BITS];       /* последние строки 1..4 — эфемеридные (бит [0] — 85-й) */
    double   tk;             /* время начала кадра (с от начала суток МДВ), −1 — нет */
    int      tb[5], have;    /* tb строк 1–4, маска принятых строк 1–5 */
    eph_t    eph;            /* последние полные эфемериды (toc — GPST, секунды недели) */
    int      eph_new;
    int      slot;           /* номер КА (строка 4) */
    int      na, n4;         /* день в четырёхлетии, номер четырёхлетия (строка 5) */
    /* привязка ко времени: конец метки времени последней строки (номер отсчёта) и её время */
    int      str_m;          /* номер последней строки (1..15) */
    uint64_t str_end_n;
    double   str_end_tod;    /* время конца строки, с от начала суток МДВ (−1 — нет tk) */
    int      n_str, n_err;
} glonav_t;

void glonav_init(glonav_t *g, int fcn);
/* очередной символ (10 мс): мягкое значение, n_end — номер последнего отсчёта символа.
 * Возвращает номер принятой строки (1..15) или 0. */
int  glonav_sym(glonav_t *g, double v, uint64_t n_end);
/* перевод времени суток МДВ в GPST (секунды недели) по приближённому GPST t_ref */
double glo_tod2gpst(double tod, double t_ref);
/* время МДВ (N4 — номер четырёхлетия с 1996 г., NA — сутки в четырёхлетии, tod — с от начала
 * суток) -> GPST: неделя и секунды недели (без шкалы приёмника, для работы только по ГЛОНАСС) */
double glo_date2gpst(int n4, int na, double tod, int *week);

/* проверка кода Хэмминга строки (биты 85..1, s[0] — бит 85); 1 — без ошибок */
int  glo_str_check(const uint8_t *s);
/* кодирование (для проверок и имитатора): строка m (1..5 — из эфемерид, 6..15 — пустые)
 * с кодом Хэмминга; tk — время начала кадра (с от начала суток МДВ) */
void glo_str_encode(const eph_t *e, int m, double tk, int slot, uint8_t *s);
/* символы строки (200 × ±1: 170 символов данных + 30 метки времени) */
void glo_str_symbols(const uint8_t *s, int8_t *sym);

#endif
