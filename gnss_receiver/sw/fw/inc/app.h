/* МГП-8: прикладной уровень ПО МК — работа приёмника без привязки к периферии МК (на ПК
 * проверяется на модели ПЛИС, tests/test_app.c).
 *
 * Три уровня выполнения:
 *  - прерывание ПЛИС (app_irq; на МК — EXTI PE5, высший приоритет): результаты корреляторов,
 *    петли слежения, навигационные сообщения, пуск каналов второй частоты (rx_process);
 *    фиксация измерений на эпоху (rx_latch) сразу после чтения результатов. Прерывание TIC
 *    каждые 1 мс гарантирует вызов не реже 1 мс независимо от числа каналов;
 *  - решение (app_sol; на МК — PendSV, запрашивается из app_irq): навигационное решение по
 *    копии измерений и эфемерид, момент 1PPS, выдача NMEA — не ждёт окончания поиска;
 *  - фон (app_poll из главного цикла): снимки отсчётов и поиск КА по одному с пуском канала
 *    сразу после поиска (поиск одного КА на МК — до сотен миллисекунд); затем второй проход —
 *    поиск на ускорителе ПЛИС (acq_hw_*, накопление hw_K периодов; при hw_K = 256 — до 29 дБГц)
 *    КА, не найденных первым, с пуском канала в режиме слабого сигнала (trk_cfg_t.weak). Второй
 *    проход — по L1 C/A; один КА в диапазоне доплера ±6 кГц — ≈ 2,1 с при hw_K = 256. Кандидат
 *    (z ≥ APP_HW_T1) подтверждается накоплением 2·hw_K периодов в ячейке доплера кандидата и
 *    двух соседних (≈ 1,6 с): канал пускается, если максимум — на месте кандидата (±APP_HW_DP
 *    чипа). Каналы слабого сигнала проверяются на ложный захват взаимно-корреляционного пика
 *    сильного КА (rx_xcheck, на каждом вызове app_poll).
 * Каналы, пул декодеров, эфемериды и измерения общие: решение и фон изменяют и копируют их под
 * блокировкой (rx_t.lock; на МК — BASEPRI маскирует прерывание ПЛИС и PendSV на десятки
 * микросекунд, поэтому блокировки не вкладываются). */
#ifndef APP_H
#define APP_H
#include <stdint.h>
#include "rx.h"
#include "max2771.h"

#define APP_NSNAP     4                 /* снимков на серию */
#define APP_SNAP_N    49152             /* отсчётов в снимке (2,048 мс; 24 КБ) */
#define APP_MAXSIG    8
#define APP_TIC       24000u            /* период TIC, отсчётов (1 мс) */
#define APP_EPOCH     24000000ull       /* период измерений, отсчётов (1 с) */
#define APP_SNAP_AGE  12000000ull       /* предельный возраст снимков для поиска, отсчётов (0,5 с):
                                           ошибка доплера ±125 Гц уводит фазу кода L1 на 0,04 чипа */
#define APP_LATCH_MAX 1200000ull        /* предельное опоздание фиксации, отсчётов (50 мс) */
#define APP_PPS_HOLD  60.0              /* 1PPS по последнему решению не дольше, с */
#define APP_PPS_LEAD  48000ull          /* запись PPS_T не позже чем за 0,5 мс, такты 96 МГц */
#define APP_HW_T1     5.5               /* порог z кандидата ускорителя и результата подтверждения */
#define APP_HW_DP     1.0               /* допуск места пика при подтверждении, чипы */

/* код возврата app_poll и app_sol — выполненная работа */
enum { APP_IDLE = 0, APP_SNAP = 1, APP_ACQ = 2, APP_SOL = 4, APP_HW = 8 };
/* ошибки app_init (биты) */
enum { APP_E_FPGA = 1, APP_E_RF = 2 };

typedef struct {
    rx_t      *rx;
    uint8_t   *snap[APP_NSNAP];         /* буферы снимков по SNAP_BYTES(APP_SNAP_N) (на МК — DTCM) */
    void     (*out)(const char *s, int n);   /* вывод NMEA (NULL — нет) */
    /* настройки (после app_init, до разрешения прерывания) */
    acq_cfg_t  ac;
    int        sig[APP_MAXSIG], nsig;   /* сигналы поиска (по очереди) */
    double     acq_period;              /* повторный поиск невидимых КА, с */
    int        hw_K;                    /* периодов накопления ускорителя (0 — без второго прохода) */
    /* состояние ПЛИС и ВЧ-тракта */
    uint32_t   fpga_ver;
    int        nch;                     /* каналов коррелятора */
    max_status_t rf;
    /* фон: поиск */
    int        st, si, q, q1, k, snap_rf;
    int        pass;                    /* 0 — поиск по снимкам, 1 — на ускорителе */
    uint32_t   t0[APP_NSNAP];
    uint64_t   acq_next;
    acq_hw_t   hw;
    /* фон: решение и 1PPS */
    uint32_t   seq_done;
    uint32_t   pps_seen;
    double     pps_sec, pps_qerr;       /* секунда GPST взведённого 1PPS и его qErr, с */
    /* общие с прерыванием */
    volatile uint32_t seq;              /* число фиксаций измерений */
    uint64_t   lat_m, next_m;           /* отсчёт последней и следующей эпохи */
    int        lat_n;                   /* измерений с эфемеридами в последней фиксации */
    volatile uint32_t n_irq, n_tic, n_pps, n_late;
    /* статистика фона */
    uint32_t   n_acq, n_found, n_sol, n_fail, n_nmea;
    uint32_t   n_hw, n_hw_found;        /* поисков на ускорителе, найдено */
    uint32_t   n_xc;                    /* из найденных — ложных (взаимная корреляция, rx_xcheck) */
    int        hw_c;                    /* идёт подтверждение кандидата (z ≥ APP_HW_T1) */
    acq_res_t  hw_res;                  /* кандидат: результат и отсчёт начала его запуска */
    uint32_t   hw_tr;
    int        hw_q;                    /* последний поиск на ускорителе: КА, z, результат rx_start */
    double     hw_z;
    int        hw_s;
} app_t;

/* ПЛИС (ID, версия, корреляторы), ВЧ-тракт (MAX2771), приёмник, TIC и маска прерываний ПЛИС.
 * lock — блокировка (на МК — запрет прерывания ПЛИС; NULL — без блокировки).
 * 0 — успешно, иначе биты APP_E_*: без ПЛИС работа невозможна, при ошибке ВЧ-канала
 * приёмник работает по остальным */
int  app_init(app_t *a, rx_t *r, uint8_t *const *snap, void (*lock)(int on));
int  app_irq(app_t *a);                 /* обработчик прерывания ПЛИС; 1 — нужен вызов app_sol */
int  app_sol(app_t *a);                 /* решение, 1PPS, NMEA (APP_SOL — получено решение) */
int  app_poll(app_t *a);                /* шаг поиска (APP_SNAP, APP_ACQ, APP_HW — поиск КА на ускорителе
                                           завершён) */

#endif
