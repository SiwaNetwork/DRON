/* МГП-8: навигационное сообщение BeiDou D1 (BDS-SIS-ICD-B1I-3.0, п. 5.2), КА MEO/IGSO.
 * Подкадр — 300 бит (6 с, 50 бит/с после снятия кода NH): слово 1 — синхрокомбинация 11100010010,
 * 4 бит резерва и кодовое слово BCH(15,11); слова 2–10 — по два слова BCH(15,11), перемежённых
 * по битам. Подкадры 1–3 — время, часы, ионосфера (Клобучар), эфемериды. SOW — BDT переднего
 * фронта синхрокомбинации; GPST = BDT + 14 с, неделя GPS = WN + 1356. Раскладка полей — по
 * 300-битовому подкадру после декодирования BCH (проверочные биты на своих местах: в слове
 * 2–10 — 11 + 11 информационных, 4 + 4 проверочных). D2 (КА GEO, 500 бит/с) — не реализовано. */
#ifndef BDSNAV_H
#define BDSNAV_H
#include <stdint.h>
#include "eph.h"

#define BDS_GPS_WEEK 1356        /* неделя GPS начала недели BDT 0 (01.01.2006) */

typedef struct {
    int      prn;
    uint8_t  win[311];           /* последние 311 бит (подкадр и синхрокомбинация следующего) */
    int      nbit;
    int      sync, pol, cnt, miss;
    uint8_t  sf[5][38];          /* подкадры 1–5 после декодирования BCH */
    int      sow_sf[3];          /* SOW подкадров 1–3 (сборка эфемерид в одном кадре) */
    int      nc_sf[3];           /* исправлений BCH в подкадрах 1–3 */
    uint8_t  prev[3][38];        /* подкадры 1–3 предыдущего кадра (сверка при исправлениях) */
    int      prev_ok;
    int      sow_prev;           /* SOW предыдущего подкадра (−1 — нет) */
    eph_t    eph;                /* последние полные эфемериды */
    int      eph_new;
    double   ion[8];             /* α0..α3, β0..β3 */
    int      ion_ok;
    int      week;               /* неделя GPS, 0 — неизвестна */
    /* последний подкадр: номер последнего отсчёта, GPST (с недели) его конца = начала следующего */
    int      tow_ok;
    uint64_t sf_end_n;
    double   sf_end_tow;
    int      n_sf, n_corr, n_sow_err;
} bdsnav_t;

void bdsnav_init(bdsnav_t *b, int prn);
/* очередной бит (20 мс, после снятия NH); n_end — номер последнего отсчёта бита. Возвращает
 * номер подкадра 1–5, если подкадр принят и привязан ко времени (SOW согласован с предыдущим):
 * момент n_end + 1 соответствует GPST b->sf_end_tow. */
int  bdsnav_bit(bdsnav_t *b, int bit, uint64_t n_end);
/* кодирование подкадра sfid (1–3 — по эфемеридам, 4–5 — псевдослучайные данные) с SOW (BDT
 * начала подкадра) в 300 бит линии (для проверок и имитатора) */
void bdsnav_encode(const eph_t *e, int sfid, int sow, uint8_t bits[300]);
/* служебные (для проверок): кодирование и исправление слова BCH(15,11), старший бит первым */
uint32_t bdsnav_bch_enc(uint32_t info11);
uint32_t bdsnav_bch_dec(uint32_t cw15, int *nerr);

#endif
