"""Расчёт надёжности МГП-8 (ТЗ п. 5.5.1) — метод подсчёта элементов (parts count).

Перечень элементов — модель схемы Э3 (hw/gen/design.py). Интенсивности отказов λ (1/ч·10^-6) —
обобщённые значения для промышленной элементной базы при температуре корпуса +40 °С в нормальных
условиях (уровень оценок справочника «Надёжность ЭРИ» и FIDES для изделий коммерческого
исполнения); для условий эксплуатации на борту БАС применяется коэффициент жёсткости K_э.
Отказ любого элемента считается отказом изделия (последовательная схема надёжности).
"""
import os
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "hw", "gen"))
import design  # noqa: E402

# λ микросхем по типу (по обозначению изготовителя)
IC = [("LFE5U", 0.15, "ПЛИС"), ("STM32", 0.10, "микроконтроллер"), ("CYUSB", 0.10, "контроллер USB 3.0"),
      ("MAX2771", 0.05, "ВЧ-приёмник"), ("", 0.02, "прочие (питание, логика, интерфейсы, память)")]
GROUP = {"Резисторы": 0.0015, "Конденсаторы": 0.002, "Катушки индуктивности": 0.002, "Диоды": 0.003,
         "Индикаторы": 0.005, "Элементы СВЧ": 0.01, "Резонаторы": 0.02, "Генераторы": 0.03,
         "Предохранители": 0.01, "Соединители": 0.02, "Фильтры и дроссели": 0.002}
BOARD = [("Печатная плата (8 слоёв, ~2500 переходных отверстий)", 0.05),
         ("Паяные соединения (~2300, в т. ч. BGA)", 0.10)]
K_E = 2.5            # жёсткость условий: бортовая аппаратура БАС (вибрация, термоциклы)


def main():
    d = design.build()
    comps = [c for c in d.comps if not c.dnp]
    rows, lam = [], 0.0
    ics = [c for c in comps if c.pd.group == "Микросхемы"]
    used = set()
    for key, l, name in IC:
        n = sum(1 for c in ics if key in c.pd.pn and id(c) not in used)
        for c in ics:
            if key in c.pd.pn:
                used.add(id(c))
        rows.append((f"Микросхемы: {name}", n, l, n * l))
        lam += n * l
    cnt = Counter(c.pd.group for c in comps if c.pd.group != "Микросхемы")
    for g, n in sorted(cnt.items(), key=lambda x: -x[1]):
        l = GROUP.get(g, 0.01)
        rows.append((g, n, l, n * l))
        lam += n * l
    for name, l in BOARD:
        rows.append((name, 1, l, l))
        lam += l
    mtbf = 1e6 / lam
    mtbf_e = 1e6 / (lam * K_E)
    out = ["### Расчёт надёжности (метод подсчёта элементов)", "",
           "| Группа элементов | Кол-во | λ элемента, 10⁻⁶ 1/ч | λ группы, 10⁻⁶ 1/ч |", "|---|---|---|---|"]
    for name, n, l, s in rows:
        out.append(f"| {name} | {n} | {l:.4f} | {s:.3f} |")
    out.append(f"| **Итого (нормальные условия)** | {sum(r[1] for r in rows)} |  | **{lam:.3f}** |")
    out += ["", f"Средняя наработка на отказ: в нормальных условиях T₀ = 10⁶/Λ = {mtbf:,.0f} ч; "
                f"в условиях эксплуатации на борту БАС (K_э = {K_E}) — **{mtbf_e:,.0f} ч**, "
                f"что удовлетворяет требованию ТЗ (не менее 50 000 ч) с запасом {mtbf_e / 50000:.1f} раза.".replace(",", " "),
            "", "Вероятность безотказной работы за 1000 ч полёта на борту БАС: "
                f"P = exp(−Λ·K_э·t) = {pow(2.718281828, -lam * K_E * 1000e-6):.4f}."]
    os.makedirs(os.path.join(HERE, "out"), exist_ok=True)
    open(os.path.join(HERE, "out", "reliability.md"), "w").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
