"""Расчёт потребляемой мощности и тепловой режим МГП-8 (ТЗ п. 5.4.2, 5.6.1).

Токи потребления — типовые значения из технической документации изготовителей при принятых
режимах; ток ядра ПЛИС — оценка для 58 % логики LFE5U-45 на 96 МГц (Lattice Power Calculator,
коэффициент переключений 12,5 %). Структура питания — по схеме Э3 (hw/gen/design.py):
+5V_SYS -> TPS62130 (+3V3D, +1V1), LP5907 (ВЧ-каналы, тактирование), LP5907 2,5 В от +3V3D;
FX3 питается от VBUS (ядро 1,2 В — TPS62130, VIO 3,3 В — SPX3819) и работает только в режиме
выдачи отсчётов по USB.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# нагрузка: (шина, потребитель, ток мА, примечание)
LOADS = [
    ("+3V3_RF", "MAX2771 × 8 (ВЧ-каналы, режим высокой линейности)", 8 * 19.0, "ICC тип."),
    ("+3V3_CLK", "ТКГ TG2520SMN, буфер 74FCT3807", 2.0 + 25.0, ""),
    ("+1V2_CLK", "Буферы 74AVC9112 × 2", 8.0, ""),
    ("+1V1", "ПЛИС LFE5U-45: ядро (VCC)", 420.0, "оценка Power Calculator"),
    ("+2V5", "ПЛИС: VCCAUX", 25.0, ""),
    ("+3V3D", "ПЛИС: банки ввода-вывода (VCCIO)", 45.0, ""),
    ("+3V3D", "МК STM32H743, 480 МГц, ядро и периферия", 185.0, "IDD, VOS0"),
    ("+3V3D", "Флеш-память конфигурации, EEPROM", 6.0, ""),
    ("+3V3D", "Карта microSD (запись)", 40.0, "среднее"),
    ("+3V3D", "Датчик тока, компаратор, буферы 1PPS/EXTINT, светодиоды", 12.0, ""),
    ("+5V_SYS", "Приёмопередатчик CAN FD MCP2562FD (активный)", 10.0, "рецессив/доминант средн."),
    ("+5V_USB", "FX3 CYUSB3014: ядро 1,2 В (через TPS62130)", 210.0, "режим USB 3.0"),
    ("+5V_USB", "FX3: VIO 3,3 В (через SPX3819)", 45.0, ""),
]
# преобразователи: шина -> (источник, тип, КПД или падение)
REG = {
    "+3V3_RF": ("+5V_SYS", "LDO"), "+3V3_CLK": ("+5V_SYS", "LDO"), "+1V2_CLK": ("+3V3_CLK", "LDO"),
    "+1V1": ("+5V_SYS", "BUCK"), "+2V5": ("+3V3D", "LDO"), "+3V3D": ("+5V_SYS", "BUCK"),
}
V = {"+3V3_RF": 3.3, "+3V3_CLK": 3.3, "+1V2_CLK": 1.2, "+1V1": 1.1, "+2V5": 2.5, "+3V3D": 3.3,
     "+5V_SYS": 5.0, "+5V_USB": 5.0}
ETA_BUCK = {"+1V1": 0.80, "+3V3D": 0.88}       # TPS62130, при данных токах (кривые КПД изготовителя)
THETA = [("ПЛИС LFE5U-45 (caBGA381)", 17.7, None), ("МК STM32H743 (LQFP100)", 38.0, None),
         ("Контроллер FX3 (BGA121)", 25.0, None), ("LP5907 ВЧ-канала (SOT-23-5)", 160.0, None)]


def main():
    cur = {k: 0.0 for k in V}
    for bus, _, i, _ in LOADS:
        cur[bus] += i
    # каскад: от нижних шин к верхним
    loss = {}
    for bus in ("+1V2_CLK", "+2V5", "+3V3_CLK", "+3V3_RF", "+1V1", "+3V3D"):
        src, kind = REG[bus]
        p_out = V[bus] * cur[bus]
        if kind == "LDO":
            cur[src] += cur[bus]
            loss[bus] = (V[src] - V[bus]) * cur[bus]
        else:
            p_in = p_out / ETA_BUCK[bus]
            cur[src] += p_in / V[src]
            loss[bus] = p_in - p_out
    p_sys = V["+5V_SYS"] * cur["+5V_SYS"]
    p_ideal = 0.05 * (cur["+5V_SYS"] * 1e-3) ** 2 * 1e3       # MAX40200: ~50 мОм, мВт
    # FX3: ядро 1,2 В — импульсный стабилизатор (КПД 0,80), VIO 3,3 В — линейный SPX3819
    p_fx3_core = 1.2 * 210.0 / 0.80
    p_fx3_vio = 5.0 * 45.0
    p_usb = p_fx3_core + p_fx3_vio
    total_nav = (p_sys + p_ideal) / 1e3
    total_usb = total_nav + p_usb / 1e3
    out = ["### Потребляемая мощность", "",
           "| Шина | Потребители | Ток, мА | Мощность, мВт |", "|---|---|---|---|"]
    for bus, name, i, note in LOADS:
        out.append(f"| {bus} | {name}{' (' + note + ')' if note else ''} | {i:.0f} | {V[bus] * i if bus not in ('+5V_USB',) else (1.2 if '1,2' in name else 3.3) * i:.0f} |")
    out += ["", "| Преобразователь | Выходной ток, мА | Потери, мВт |", "|---|---|---|"]
    for bus, l in loss.items():
        out.append(f"| {REG[bus][1]} {REG[bus][0]} → {bus} | {cur[bus]:.0f} | {l:.0f} |")
    p_fx3_ldo = (1.2 * 210.0 / 0.80 - 1.2 * 210.0) + (5.0 - 3.3) * 45
    out += ["", f"Ток шины +5V_SYS: {cur['+5V_SYS']:.0f} мА; мощность от источника 5 В в навигационном режиме "
                f"(USB 3.0 не активен): **{total_nav:.2f} Вт**; в режиме выдачи отсчётов по USB 3.0 "
                f"(дополнительно FX3 {p_usb / 1e3:.2f} Вт, из них потери в стабилизаторах {p_fx3_ldo / 1e3:.2f} Вт): "
                f"**{total_usb:.2f} Вт**. Требование ТЗ — не более 3,5 Вт — выполняется "
                f"(запас {3.5 - total_usb:.2f} Вт).", ""]
    # тепловой режим
    p_fpga = (1.1 * 420 / ETA_BUCK["+1V1"] * 0 + 1.1 * 420 + 2.5 * 25 + 3.3 * 45) / 1e3
    p_mcu = 3.3 * 185 / 1e3
    p_fx3 = (1.2 * 210 + 3.3 * 45) / 1e3
    p_ldo_rf = (5.0 - 3.3) * 2 * 19.0 / 1e3
    pw = [p_fpga, p_mcu, p_fx3, p_ldo_rf]
    out += ["### Тепловой режим (температура окружающей среды +85 °С, естественная конвекция)", "",
            "| Элемент | Мощность, Вт | θJA, °С/Вт | Перегрев, °С | Tj при +85 °С | Допустимая Tj |", "|---|---|---|---|---|---|"]
    lim = [100, 105, 100, 125]
    for (name, th, _), p, tj in zip(THETA, pw, lim):
        out.append(f"| {name} | {p:.2f} | {th:.1f} | {p * th:.1f} | {85 + p * th:.1f} | {tj} |")
    out += ["", "θJA — по данным изготовителей для платы JEDEC 2s2p. Выводы и меры:", "",
            "- МК при 480 МГц превышает допустимую температуру кристалла исполнения «6» (105 °С), поэтому "
            "при температуре платы выше +70 °С (датчик температуры МК) частота ядра снижается до 400 МГц "
            "(режим VOS1, ток ≈ 140 мА): Tj ≤ 85 + 0,46·38 = 102,6 °С; вычислительной производительности "
            "400 МГц достаточно (загрузка ядра — ПЗ, разд. 7).",
            "- ПЛИС: запас 3 °С недостаточен, поэтому ПЛИС через теплопроводящую прокладку "
            "(3 Вт/(м·К), 1 мм) отводит тепло на крышку корпуса: θJA ≈ 9 °С/Вт, Tj ≈ 91 °С.",
            "- Тепловые переходные отверстия под корпусами ПЛИС и МК и сплошные слои земли 8-слойной платы "
            "дополнительно уменьшают θJA на 20–30 % (в расчёте не учитывалось).",
            "- Оценка по θJA относится к одной микросхеме на испытательной плате; нагрев платы всеми "
            "источниками (3,3 Вт на 100 × 75 мм) учитывает тепловая модель платы sim/thermal_board.py "
            "(sim/out/thermal.md): по ней на крышку корпуса отводят тепло ПЛИС, МК и FX3."]
    open(os.path.join(HERE, "out", "power.md"), "w").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
